// Base64-embed YOUR claim form template into core/templates.local.js (gitignored), so local previews and
// `node tools/build.mjs --local` can fill it with no network access. In Muse, the space returns the same
// file from its getClaimTemplate action instead.
//   node tools/embed-templates.mjs path/to/claim-form.xlsx
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, basename } from 'node:path';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const file = process.argv[2];
if (!file) { console.error('Usage: node tools/embed-templates.mjs path/to/claim-form.xlsx'); process.exit(1); }
const buf = await readFile(file);
if (buf.readUInt32LE(0) !== 0x04034b50) throw new Error(`${file} is not an .xlsx file`);
const out = `/* Generated by tools/embed-templates.mjs from ${basename(file)} (${buf.length} bytes). Local only: never commit. */
(function () {
  const CF = (window.CF = window.CF || {});
  CF.templates = { claim: '${buf.toString('base64')}' };
})();
`;
await writeFile(join(ROOT, 'core/templates.local.js'), out);
console.log(`✓ core/templates.local.js  ${(out.length / 1024).toFixed(1)} KB`);
